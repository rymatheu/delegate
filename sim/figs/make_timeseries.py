#!/usr/bin/env python3
"""flight-timeseries.tex: position, attitude, heading and actuators of the 1 m/s figure-eight course
against time, from sim/out/lean-course-1ms and sim/out/ref-course-1ms (flight.csv, summary.txt).

    sim/.venv/bin/python sim/figs/make_timeseries.py [--out DIR]   (default: the staging figs folder)
"""
from __future__ import annotations

import argparse
import math
from pathlib import Path

import numpy as np

import common as C

N_PTS = 400                       # points per curve (largest-triangle-three-buckets)
X0, WIDTH = 0.84, 7.17            # plotting area, cm
TOP = 5.77                        # top of the hairlines, cm
# panels: (name, data range, bottom cm, height cm)
PANELS = {
    "position": ((-2.75, 2.75), 4.50, 1.22),
    "attitude": ((-32.0, 32.0), 3.00, 1.22),
    "heading": ((-20.0, 340.0), 1.50, 1.22),
    "motors": ((0.36, 0.51), 0.00, 1.22),
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(C.STAGING / "figs"))
    args = ap.parse_args()
    lean_dir, ref_dir = C.run_dir("lean"), C.run_dir("ref")
    L, R = C.load_flight(lean_dir), C.load_flight(ref_dir)
    ndiff = C.check_same(L, R)
    if ndiff:
        raise SystemExit(f"the two flights differ on {ndiff} ticks; this figure assumes they coincide")
    S = C.summary(lean_dir)
    t = L["t"]
    tmax = float(t[-1])
    kx = WIDTH / tmax
    angle_max = C.angle_max_deg()        # ATC_ANGLE_MAX in effect (both vehicles' --print-params)

    def series(F):
        return {
            "position": [(F["x_n"], "fwOchre"), (F["y_e"], "fwBlue"), (F["z_d"], "fwMute")],
            "attitude": [(np.degrees(F["roll"]), "fwOchre"), (np.degrees(F["pitch"]), "fwBlue")],
            "heading": [(np.degrees(np.unwrap(F["yaw"])), "fwBlue")],
            "motors": [(F["m1"], "fwOchre"), (F["m2"], "fwBlue"), (F["m3"], "fwVerm"), (F["m4"], "fwMute")],
        }
    targets = {
        "position": [L["sp_n"], L["sp_e"], L["sp_d"]],
        "attitude": [np.degrees(L["roll_t"]), np.degrees(L["pitch_t"])],
        "heading": [np.degrees(np.unwrap(L["yaw_t"]))],
        "motors": [],
    }
    SL, SR = series(L), series(R)

    def thin(y, name):
        (lo, hi), _, h = PANELS[name]
        ky = h / (hi - lo)
        idx = C.lttb(np.stack([t * kx, y * ky], axis=1), N_PTS)
        if y.min() < lo or y.max() > hi:
            raise SystemExit(f"{name}: data {y.min():.3f}..{y.max():.3f} outside the axis {lo}..{hi}")
        return t[idx], y[idx]

    wps = S["waypoints"]
    out = []
    w = out.append
    w("% ==================================================================")
    w("%  Flight time series -- one sigconf text width (8.2 cm), pdfLaTeX, plain TikZ")
    w("%  Preamble:  \\usepackage{tikz}  (no pgfplots; coordinates are embedded)")
    w(f"%  Data:      cpp2lean {C.rel(lean_dir / 'flight.csv')} (copter_lean, the")
    w("%             Lean translations of ArduPilot's classes) and")
    w(f"%             {C.rel(ref_dir / 'flight.csv')} (copter_ref, ArduPilot's")
    w("%             classes compiled unmodified); params copter-cf2x.txt +")
    w("%             copter-course-speed.txt + copter-cf2x-tuned.txt (tuned gains),")
    w(f"%             {len(t)} ticks at 400 Hz (physics 1200 Hz), t = 0 to {tmax:g} s. The")
    w("%             two flights are equal in every field of flight.csv on every")
    w("%             tick (checked by the script; only the controller round-trip")
    w("%             time differs), so each copter_ref curve is drawn as a pale wide")
    w("%             stroke of the same color under the copter_lean curve, and each")
    w(f"%             target once. Each curve thinned to {N_PTS} points by")
    w("%             largest-triangle-three-buckets (areas measured on the page),")
    w("%             values rounded to 3 decimals.")
    w("%  Mission:   the figure-eight course at WP_SPD 1 m/s, WP_ACC 1.5 m/s^2.")
    w("%  Panels:    position (NED, m) with AC_PosControl's desired position dashed")
    w("%             (trace fields sp_n, sp_e, sp_d); roll and pitch (deg) with the")
    w("%             attitude-target Euler angles dashed (roll_t, pitch_t) and the")
    w(f"%             {angle_max:g} deg lean limit ATC_ANGLE_MAX (value in effect, from the")
    w("%             vehicles' --print-params); heading (deg, unwrapped) with the")
    w("%             attitude-target yaw dashed (yaw_t); actuators m1..m4 of motor")
    w("%             slots 0..3.")
    w("%  Hairlines: closest approach to w_i (i = 0..7), from summary.txt of the")
    w("%             same run: " + ", ".join(f"{x['t_closest']:g}" for x in wps) + " s.")
    w("%  Generated by cpp2lean sim/figs/make_timeseries.py from the files above;")
    w("%  no hand-edited coordinates.")
    w("% ==================================================================")
    w(C.PALETTE)
    w("""\\begin{tikzpicture}[
  x=1cm, y=1cm, line cap=round, line join=round,
  tick/.style={font=\\scriptsize, text=fwMute, inner sep=1pt},
  ylab/.style={font=\\scriptsize, text=fwInk!80, rotate=90, anchor=south, inner sep=0},
  axis/.style={draw=fwHair, line width=0.4pt},
  mk/.style={draw=fwHair, line width=0.4pt},
  sw/.style={draw=fwHair, line width=0.3pt},
  tgt/.style={draw=fwMute, line width=0.35pt, dash pattern=on 1.6pt off 1.1pt},
  thr/.style={draw=fwVerm!75, line width=0.35pt, dash pattern=on 2.2pt off 1.3pt},
  crv/.style={line width=0.5pt},
  ref/.style={line width=1.4pt, draw opacity=0.25},
  key/.style={font=\\scriptsize, inner sep=1pt},
]""")
    w("% ---------------- closest approaches (all panels)")
    for x in wps:
        xc = X0 + x["t_closest"] * kx
        w(f"\\draw[sw] ({xc:.3f},0.000) -- ({xc:.3f},{TOP:.3f});")
        w(f"\\node[tick, anchor=south] at ({xc:.3f},{TOP - 0.03:.3f}) {{$w_{x['i']}$}};")
    # the longest stretch between consecutive closest approaches holds the in-panel labels
    tc = [x["t_closest"] for x in wps]
    gaps = [(tc[i + 1] - tc[i], (tc[i] + tc[i + 1]) / 2) for i in range(len(tc) - 1)]
    t_mid = max(gaps)[1]
    ticks_t = list(range(0, int(tmax) + 1, 4))
    for name, ((lo, hi), y0, h) in PANELS.items():
        ky = h / (hi - lo)
        sy = y0 - lo * ky
        w(f"% ---------------- {name}")
        w(f"\\begin{{scope}}[shift={{({X0},{C.num(sy, 4)})}}, x={C.num(kx, 5)}cm, y={C.num(ky, 6)}cm]")
        w(f"  \\draw[axis] (0,{C.num(hi)}) -- (0,{C.num(lo)}) -- ({C.num(tmax, 4)},{C.num(lo)});")
        yt = {"position": [(-2, "$-2$"), (0, "$0$"), (2, "2\\,m")],
              "attitude": [(-30, "$-30$"), (0, "$0$"), (30, "$30^\\circ$")],
              "heading": [(0, "$0$"), (90, "$90$"), (180, "$180$"), (270, "$270^\\circ$")],
              "motors": [(0.40, "$0.40$"), (0.45, "$0.45$"), (0.50, "$0.50$")]}[name]
        for v, lab in yt:
            w(f"  \\draw[mk] (0,{C.num(v)}) -- ++(-0.06cm,0) node[tick, anchor=east] {{{lab}}};")
        for v in ticks_t:
            w(f"  \\draw[mk] ({v},{C.num(lo)}) -- ++(0,-0.06cm);")
        if name == "attitude":
            w(f"  \\draw[thr] (0,{C.num(angle_max)}) -- ({C.num(tmax, 4)},{C.num(angle_max)});")
            w(f"  \\draw[thr] (0,{C.num(-angle_max)}) -- ({C.num(tmax, 4)},{C.num(-angle_max)});")
        for (y, col) in SR[name]:
            tt, yy = thin(y, name)
            w(f"  \\draw[ref, {col}] plot coordinates {{  % copter_ref\n" + C.coords(tt, yy) + "\n  };")
        for y in targets[name]:
            tt, yy = thin(y, name)
            w("  \\draw[tgt] plot coordinates {\n" + C.coords(tt, yy) + "\n  };")
        for (y, col) in SL[name]:
            tt, yy = thin(y, name)
            w(f"  \\draw[crv, {col}] plot coordinates {{  % copter_lean\n" + C.coords(tt, yy) + "\n  };")
        if name == "position":
            w(f"  \\node[key, anchor=east] at ({C.num(tmax, 4)},2.05) {{\\textcolor{{fwOchre}}{{north}}\\ \\ "
              "\\textcolor{fwBlue}{east}\\ \\ \\textcolor{fwMute}{down}};")
        if name == "attitude":
            w(f"  \\node[key, text=fwOchre, anchor=west] at ({C.num(t_mid - 0.6)},-24) {{roll}};")
            w(f"  \\node[key, text=fwBlue, anchor=west] at ({C.num(t_mid - 0.6)},22) {{pitch}};")
        if name == "heading":
            # key of the line styles, top left (the heading is still low there)
            w("  \\draw[ref, fwInk] (0.35,300) -- (1.35,300);")
            w("  \\draw[crv, fwInk] (0.35,300) -- (1.35,300);")
            w("  \\node[key, text=fwMute, anchor=west, fill=white] at (1.5,300) {Lean over C++};")
            w("  \\draw[tgt] (0.35,235) -- (1.35,235);")
            w("  \\node[key, text=fwMute, anchor=west, fill=white] at (1.5,235) {target};")
        if name == "motors":
            w(f"  \\node[key, anchor=east] at ({C.num(tmax, 4)},0.503) {{\\textcolor{{fwOchre}}{{$m_1$}}\\ "
              "\\textcolor{fwBlue}{$m_2$}\\ \\textcolor{fwVerm}{$m_3$}\\ \\textcolor{fwMute}{$m_4$}};")
        w("\\end{scope}")
        w(f"\\node[ylab] at (0.06,{C.num(y0 + h / 2)}) {{{name}}};")
    for v in ticks_t:
        lab = f"{v}\\,s" if v == ticks_t[-1] else f"${v}$"
        w(f"\\node[tick, anchor=north] at ({X0 + v * kx:.3f},-0.060) {{{lab}}};")
    w(f"\\node[tick, anchor=north, text=fwInk!80] at ({X0 + WIDTH / 2:.3f},-0.360) {{time}};")
    w("\\end{tikzpicture}%")
    dst = Path(args.out) / "flight-timeseries.tex"
    dst.write_text("\n".join(out) + "\n")
    print(f"{dst}: flights equal on all {len(t)} ticks; t = 0..{tmax}; label stretch centered at {t_mid:.3f} s")


if __name__ == "__main__":
    main()
