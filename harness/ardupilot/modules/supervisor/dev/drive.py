#!/usr/bin/env python3
"""Drive the supervisor executable over the module protocol, for development runs.

  python3 -I ardupilot/modules/supervisor/dev/drive.py SCENARIO [--steps N]   (from the harness directory)

Scenarios (inputs at rest: level attitude, at the origin, still, healthy estimate, mixer shut
down, no RC unless said):
  rest       N ticks, no ground station
  gcs        a HEARTBEAT and a PARAM_REQUEST_LIST from a ground station (system 255), then N ticks;
             prints the MAVLink messages that come back, by name
  guided     as gcs, then SET_MODE GUIDED, arm (MAV_CMD_COMPONENT_ARM_DISARM), takeoff to 5 m
             (MAV_CMD_NAV_TAKEOFF); prints the command log per tick (SUP_TRACE)
MAVLink frames are built and parsed with the ardupilotmega dialect that pymavlink's mavgen
(deps/mavlink) writes to build/gen/supervisor/py/apm.py (dev/gen_pymavlink.sh).
"""
import os, struct, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
HARNESS = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
sys.path.insert(0, os.path.join(HARNESS, 'py'))
sys.path.insert(0, os.path.join(HARNESS, 'deps', 'mavlink'))
os.environ.setdefault('MAVLINK20', '1')
import module_protocol as mp  # noqa: E402
# the ardupilotmega dialect, generated by pymavlink's mavgen into build/gen/supervisor/py/apm.py
sys.path.insert(0, os.path.join(HARNESS, 'build', 'gen', 'supervisor', 'py'))
import apm as mav  # noqa: E402

SCHEMA = mp.load_schema(os.path.join(HARNESS, 'build', 'gen', 'supervisor', 'module_schema.json'))
EXE = os.path.join(HARNESS, 'build', 'modules', 'supervisor', 'supervisor')


class Proc:
    def __init__(self, env=None):
        self.p = subprocess.Popen([EXE], stdin=subprocess.PIPE, stdout=subprocess.PIPE, env=env)

    record = None

    def req(self, b, nout=0):
        if Proc.record is not None:
            Proc.record.write(b)
            Proc.record.flush()
        self.p.stdin.write(b)
        self.p.stdin.flush()
        k = self.p.stdout.read(1)
        if k != b'K':
            raise SystemExit('reply %r, exit status %s' % (k, self.p.wait()))
        return self.p.stdout.read(nout) if nout else b''

    def init(self, params):
        self.req(b'I' + mp.pack(SCHEMA['params'], params))

    def step(self, inp):
        nout = mp.record_bytes(SCHEMA['output'])
        return mp.unpack(SCHEMA['output'], self.req(b'S' + mp.pack(SCHEMA['input'], inp), nout))

    def quit(self):
        self.req(b'Q')


def params():
    return {'mav_sysid': 1, 'fltmode1': 0, 'initial_mode': 0, 'arming_skipchk': -1,
            'fs_thr_enable': 0, 'fs_gcs_enable': 0, 'rc_options': 32, 'auto_options': 2, 'gps1_type': 1}


def rest_input(k):
    t_us = 2500 * (k + 1)
    d = {f['name']: (False if f['type'] == 'bool' else 0) for f in SCHEMA['input']}
    d.update({'dt': 0.0025, 'now_us': t_us, 'now_ms': t_us // 1000, 'est_q1': 1.0,
              'est_healthy': True, 'est_initialised': True, 'est_pos_ok': True,
              'est_vel_ok': True, 'est_pos_rate_d_ok': True, 'est_origin_ok': True,
              'est_variances_ok': True, 'est_filter_status': 0x1A33F,
              'est_origin_lat_e7': 473977420, 'est_origin_lon_e7': 85455940,
              'est_origin_alt_cm': 48800, 'est_accel_ef_z': -9.80665,
              'est_gps_status': 3, 'est_gps_num_sats': 10,
              'ac_althold_lean_angle_max': 0.5236, 'ac_att_target_q1': 1.0,
              'pc_ne_max_speed': 5.0, 'pc_max_speed_up': 2.5, 'pc_max_speed_down': 1.5,
              'pc_ne_max_accel': 2.5, 'pc_d_max_accel': 2.5, 'pc_vel_d_control_ratio': 1.0,
              'thrust_vec_z': -9.80665, 'est_prearm_ok': True, 'est_ins_accel_healthy': True,
              'est_ins_gyro_healthy': True, 'est_baro_healthy': True, 'est_gps_healthy': True,
              'est_gps_hdop': 100, 'est_gps_vdop': 100, 'throttle_hover': 0.35})
    return d


def put_bytes(inp, data):
    assert len(data) <= 256
    inp['gcs_rx_len'] = len(data)
    padded = data + b'\0' * (256 - len(data))
    for w in range(64):
        inp['gcs_rx_w%02d' % w] = struct.unpack('<I', padded[4 * w:4 * w + 4])[0]


def get_bytes(out):
    raw = b''.join(struct.pack('<I', out['gcs_tx_w%02d' % w]) for w in range(64))
    return raw[:out['gcs_tx_len']]


def main():
    scen = sys.argv[1]
    n = int(sys.argv[sys.argv.index('--steps') + 1]) if '--steps' in sys.argv else 10
    if '--record' in sys.argv:   # the request stream, to replay under a debugger
        Proc.record = open(sys.argv[sys.argv.index('--record') + 1], 'wb')
    env = dict(os.environ)
    if scen == 'guided':
        env['SUP_TRACE'] = '1'
    p = Proc(env)
    p.init(params())
    gcs = mav.MAVLink(None, srcSystem=255, srcComponent=190)
    parser = mav.MAVLink(None)
    parser.robust_parsing = True
    outbox = []
    if scen in ('gcs', 'guided'):
        outbox.append(gcs.heartbeat_encode(mav.MAV_TYPE_GCS, mav.MAV_AUTOPILOT_INVALID, 0, 0, 0).pack(gcs))
        outbox.append(gcs.param_request_list_encode(1, 1).pack(gcs))
    plan = {}
    if scen == 'guided':
        plan[400] = gcs.set_mode_encode(1, mav.MAV_MODE_FLAG_CUSTOM_MODE_ENABLED, 4).pack(gcs)
        plan[800] = gcs.command_long_encode(1, 1, mav.MAV_CMD_COMPONENT_ARM_DISARM, 0,
                                            1, 0, 0, 0, 0, 0, 0).pack(gcs)
        plan[1200] = gcs.command_long_encode(1, 1, mav.MAV_CMD_NAV_TAKEOFF, 0,
                                             0, 0, 0, 0, 0, 0, 5).pack(gcs)
    counts, last = {}, None
    pending = b''.join(outbox)
    for k in range(n):
        inp = rest_input(k)
        if k in plan:
            pending += plan[k]
        if k % 400 == 0 and scen in ('gcs', 'guided'):
            pending += gcs.heartbeat_encode(mav.MAV_TYPE_GCS, mav.MAV_AUTOPILOT_INVALID, 0, 0, 0).pack(gcs)
        chunk, pending = pending[:256], pending[256:]
        put_bytes(inp, chunk)
        out = p.step(inp)
        tx = get_bytes(out)
        for m in parser.parse_buffer(tx) or []:
            name = m.get_type()
            counts[name] = counts.get(name, 0) + 1
            if name in ('COMMAND_ACK', 'STATUSTEXT') or (name == 'PARAM_VALUE' and counts[name] <= 3):
                print('tick %d <- %s' % (k + 1, m))
        state = (out['armed'], out['interlock'], out['spool_desired'], out['mode'],
                 out['land_complete'])
        if state != last:
            print('tick %d: armed=%s interlock=%s spool_desired=%d mode=%d land_complete=%s '
                  'cmds=%d errors=%d' % ((k + 1,) + state + (out['cmd_log_count'],
                                                             out['sup_internal_errors'])))
            last = state
    print('messages received by the ground station:', dict(sorted(counts.items())))
    p.quit()


main()
