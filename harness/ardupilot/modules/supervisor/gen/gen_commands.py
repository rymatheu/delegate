#!/usr/bin/env python3
"""Turn commands.txt into the supervisor's command output fields.

  python3 -I gen_commands.py COMMANDS_TXT OUT_LEAN OUT_INC

OUT_LEAN (gen/Commands.lean): `Ardupilot.Modules.Supervisor.Commands.fields`, the output fields
cmd_<stage>_<method> (bool), cmd_<stage>_<method>_seq (u32) and one field per argument.
OUT_INC (gen/out/cmd_emit.inc): `sup_emit_one(method, entry, seq, out)`, which fills a target's
fields from one command-log entry and returns false if no line of commands.txt names the method.
Files are rewritten only if their text changes.
"""
import os, re, sys

SRC, OUT_LEAN, OUT_INC = sys.argv[1:4]
TY = {'f': ('f32', 'float'), 'b': ('bool', 'bool'), 'u': ('u32', 'uint32_t'), 'i': ('i32', 'int32_t')}


def write_if_changed(path, text):
    if os.path.exists(path) and open(path).read() == text:
        return
    open(path, 'w').write(text)


rules, targets = [], {}
for n, line in enumerate(open(SRC), 1):
    line = line.split('#')[0].strip()
    if not line:
        continue
    m = re.match(r'(\S+)\s*->\s*(\w+)\s+(\w+)\s*:\s*(.*)$', line)
    if not m:
        raise SystemExit('commands.txt:%d: cannot read %r' % (n, line))
    src, stage, meth, args = m.group(1), m.group(2), m.group(3), m.group(4).split()
    parsed = []
    for a in args:
        if a == '-':
            parsed.append(None)
        else:
            nm, t = a.split(':')
            parsed.append((nm, t))
    rules.append((src, stage, meth, parsed, n))
    if stage == 'signal':
        continue
    key = (stage, meth)
    sig = [p for p in parsed if p is not None]
    if key in targets and targets[key][0] != sig:
        raise SystemExit('commands.txt:%d: %s_%s has other arguments than before' % (n, stage, meth))
    targets.setdefault(key, (sig, src))

lean = ['import Harness.Module', '',
        '/-! Generated by ardupilot/modules/supervisor/gen/gen_commands.py from ardupilot/modules/supervisor/commands.txt;',
        'do not edit. The supervisor\'s command output fields. -/', '',
        'namespace Ardupilot.Modules.Supervisor.Commands', '',
        'open Harness', '', '/-- Every command target, with its call-order and argument fields. -/',
        'def fields : List Field := [']
items = []
for (stage, meth), (sig, src) in targets.items():
    base = 'cmd_%s_%s' % (stage, meth)
    items.append('  { name := "%s", type := .bool,\n    doc := "%s called this tick" }'
                 % (base, src.split("::")[-1]))
    items.append('  { name := "%s_seq", type := .u32,\n    doc := "place of that call in the tick\'s '
                 'command log, from 1 over all stages; 0 none" }' % base)
    for nm, t in sig:
        items.append('  { name := "%s_%s", type := .%s,\n    doc := "%s: argument %s" }'
                     % (base, nm, TY[t][0], src.split("::")[-1], nm))
lean.append(',\n'.join(items))
lean += [']', '', 'end Ardupilot.Modules.Supervisor.Commands', '']
write_if_changed(OUT_LEAN, '\n'.join(lean))

inc = ['// Generated by ardupilot/modules/supervisor/gen/gen_commands.py from commands.txt; do not edit.',
       'static bool sup_emit_one(const char *method, const SupCmd &c, uint32_t seq, Output &out)',
       '{']
for src, stage, meth, parsed, n in rules:
    if stage == 'signal':
        inc.append('    if (strcmp(method, "%s") == 0) {   // commands.txt:%d: output %s' % (src, n, meth))
        inc.append('        return true;')
        inc.append('    }')
        continue
    base = 'cmd_%s_%s' % (stage, meth)
    inc.append('    if (strcmp(method, "%s") == 0) {   // commands.txt:%d' % (src, n))
    inc.append('        out.%s = true;' % base)
    inc.append('        out.%s_seq = seq;' % base)
    for k, p in enumerate(parsed):
        if p is None:
            continue
        nm, t = p
        conv = {'f': 'sup_word_f(c, %d)', 'b': '(sup_word_u(c, %d) != 0)', 'u': 'sup_word_u(c, %d)',
                'i': 'int32_t(sup_word_u(c, %d))'}[t] % k
        inc.append('        out.%s_%s = %s;' % (base, nm, conv))
    inc.append('        return true;')
    inc.append('    }')
inc += ['    return false;', '}', '',
        '// a command not called this tick keeps its argument fields at the last call\'s values',
        'static void sup_hold_args(Output &out, const Output &last)', '{']
for (stage, meth), (sig, src) in targets.items():
    base = 'cmd_%s_%s' % (stage, meth)
    if sig:
        inc.append('    if (!out.%s) {' % base)
        for nm, t in sig:
            inc.append('        out.%s_%s = last.%s_%s;' % (base, nm, base, nm))
        inc.append('    }')
inc += ['}', '']
write_if_changed(OUT_INC, '\n'.join(inc))
print('gen_commands: %d rules, %d targets, %d fields' % (
    len(rules), len(targets), sum(2 + len(s) for s, _ in targets.values())))
