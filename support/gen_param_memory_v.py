#!/usr/bin/env python3
"""The memory with the estimator World inside (README.md "Phase 5: the estimator bridge", PORT-PLAN.md 4.4).

Two back ends stay: the estimator in the value World `Estimator_lib`, everything else on the byte memory of
`cpp2lean_mem.py`. The one state is the memory state with the World inside it, and a parameter has one home: the
estimator's parameters live in the World, so every memory access to their addresses goes to the World field. This
script generates that memory from the hand-written one, textually, so that later edits of the original propagate:

  support/gen_param_memory_v.py --memory
      support/ParamMemory.lean -> support/ParamMemoryV.lean: `PMem.Mem` gets the fields `w : Estimator_lib.World` and
      `eo : Estimator_lib.Outputs`; `rd`/`wr` and the word loads and stores test one address range first and, inside
      it, read or write the World field's bits (`PMem.Bridge`, generated below); the block operations (`memcpy`,
      `memset`, `strncpy`, `halRead`) assemble each bridged field whole and set it once; every other definition is the
      original text. support/GCSMemory.lean and support/VehicleMemory.lean -> ...V.lean (their imports only).
  support/gen_param_memory_v.py --bridge
      ardupilot/out/Vehicle/VehicleBridgeMap.lean (`PMem.Bridge`: the bridged fields of THIS image, from
      ardupilot/out/Vehicle/estimator_params.json, which ardupilot/param/gen_param_harness.py computes from clang's
      offsets and Vehicle_lib.addresses.json, with each field's World path from the estimator's signatures), and the
      adapters ardupilot/out/Vehicle/VehicleBridge.lean (ardupilot/vehicle/gen_bridge.py); copies in lean/.

The originals and every golden stay byte-identical (AP_Param.json and GCS.json still import ParamMemory).
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def sub1(text, pat, rep, flags=0):
    """exactly one match of pat (the generation fails loudly when the original changes shape)"""
    n = len(re.findall(pat, text, flags))
    if n != 1:
        sys.exit("gen_param_memory_v: %d matches of %r in ParamMemory.lean" % (n, pat))
    return re.sub(pat, rep, text, count=1, flags=flags)


def insert_before(text, anchor, block):
    if text.count(anchor) != 1:
        sys.exit("gen_param_memory_v: anchor %r found %d times" % (anchor, text.count(anchor)))
    return text.replace(anchor, block + anchor, 1)


DOC = '''/-!
GENERATED by support/gen_param_memory_v.py from support/ParamMemory.lean (do not edit; edit the original or the
generator). The memory with the estimator World inside (README.md "Phase 5: the estimator bridge"): the memory state
`Mem` holds the value World of `Estimator_lib` (`w`) and its output log (`eo`). A parameter has one home: the bytes of
the estimator's parameters (the fields of `PMem.Bridge`, from clang's addresses for this image) are not in `m`; a load
or store there reads or writes the World field's bits. One range test (`Bridge.lo` .. `Bridge.hi`) keeps every other
access on the original path. A whole-field load or store is one getter or setter call; a block operation (`memcpy`,
`memset`, `strncpy`, `halRead`) assembles each bridged field from its bytes and sets it once; a lone byte store into a
field is a read-modify-write of its bits.
-/

'''

NEW_RD_WR = '''/-- (generated) an address inside the bridged range, and a block that meets it (one range test each) -/
@[inline] def inBridge (a : UInt64) : Bool := Bridge.lo ≤ a && a < Bridge.hi
@[inline] def inBridgeN (a : UInt64) (n : Nat) : Bool := n != 0 && Bridge.lo < a + n.toUInt64 && a < Bridge.hi

/-- (generated) a byte of a bridged field from the World field's bits, else the memory -/
def rdField (a : UInt64) : M UInt8 := do
  match Bridge.find a with
  | some (base, i) => return ((Bridge.get (← get).w i) >>> (8 * (a - base))).toUInt8
  | none => rdRaw a

/-- (generated) a lone byte store into a bridged field: read-modify-write of the field's bits -/
def wrField (a : UInt64) (v : UInt8) : M Unit := do
  match Bridge.find a with
  | some (base, i) =>
    let s ← get
    let sh := 8 * (a - base)
    let old := Bridge.get s.w i
    set { s with w := Bridge.set s.w i ((old &&& ~~~((0xff : UInt64) <<< sh)) ||| (v.toUInt64 <<< sh)) }
  | none => wrRaw a v

@[inline] def rd (a : UInt64) : M UInt8 := if inBridge a then rdField a else rdRaw a

@[inline] def wr (a : UInt64) (v : UInt8) : M Unit := if inBridge a then wrField a v else wrRaw a v

/-- (generated) `n` bytes from `a`, bridged bytes from their fields -/
def rdBlock (a : UInt64) (n : Nat) : M ByteArray := do
  let mut out := ByteArray.empty
  for k in [0:n] do
    out := out.push (← rd (a + k.toUInt64))
  return out

/-- (generated) store the bytes `bs` at `d`: the bytes of each bridged field are assembled into the field's bits and
the field is set once (no intermediate value of a partly written field is built) -/
def wrBlock (d : UInt64) (bs : ByteArray) : M Unit := do
  let n := bs.size
  if !inBridgeN d n then
    for k in [0:n] do
      wrRaw (d + k.toUInt64) (bs.get! k)
    return
  let mut k := 0
  while k < n do
    let a := d + k.toUInt64
    match (if inBridge a then Bridge.find a else none) with
    | some (base, i) =>
      let fend := base + (Bridge.size i).toUInt64
      let s ← get
      let mut bits := Bridge.get s.w i
      let mut j := k
      while j < n && d + j.toUInt64 < fend do
        let sh := 8 * (d + j.toUInt64 - base)
        bits := (bits &&& ~~~((0xff : UInt64) <<< sh)) ||| ((bs.get! j).toUInt64 <<< sh)
        j := j + 1
      set { s with w := Bridge.set s.w i bits }
      k := j
    | none =>
      wrRaw a (bs.get! k)
      k := k + 1

'''

NEW_LD = '''/-- (generated) an `n`-byte load meeting the bridged range: a whole field from its getter, else byte by byte -/
def ldWord (a : UInt64) (n : Nat) : M UInt64 := do
  if let some (base, i) := Bridge.find a then
    if base == a && Bridge.size i == n then
      return Bridge.get (← get).w i
  let mut v : UInt64 := 0
  for k in [0:n] do
    v := v ||| ((← rd (a + k.toUInt64)).toUInt64 <<< (8 * k).toUInt64)
  return v

@[inline] def ldU16 (a : UInt64) : M UInt16 := do
  if inBridgeN a 2 then return (← ldWord a 2).toUInt16 else ldU16Raw a
@[inline] def ldU32 (a : UInt64) : M UInt32 := do
  if inBridgeN a 4 then return (← ldWord a 4).toUInt32 else ldU32Raw a
'''

NEW_ST = '''/-- (generated) an `n`-byte store meeting the bridged range: a whole field by its setter, else assembled per field -/
def stWord (a : UInt64) (n : Nat) (v : UInt64) : M Unit := do
  if let some (base, i) := Bridge.find a then
    if base == a && Bridge.size i == n then
      modify fun s => { s with w := Bridge.set s.w i v }
      return
  let mut bs := ByteArray.empty
  for k in [0:n] do
    bs := bs.push (v >>> (8 * k).toUInt64).toUInt8
  wrBlock a bs

@[inline] def stU16 (a : UInt64) (v : UInt16) : M Unit :=
  if inBridgeN a 2 then stWord a 2 v.toUInt64 else stU16Raw a v
@[inline] def stU32 (a : UInt64) (v : UInt32) : M Unit :=
  if inBridgeN a 4 then stWord a 4 v.toUInt64 else stU32Raw a v
'''

NEW_MEM = '''/-- (generated) `memcpy`/`memset` meeting the bridged range: through `rdBlock`/`wrBlock` -/
def memcpy (d s : UInt64) (n : UInt64) : M UInt64 := do
  if inBridgeN d n.toNat || inBridgeN s n.toNat then
    wrBlock d (← rdBlock s n.toNat)
    return d
  memcpyRaw d s n

def memset (d : UInt64) (c : Int32) (n : UInt64) : M UInt64 := do
  if inBridgeN d n.toNat then
    wrBlock d (ByteArray.mk (Array.replicate n.toNat c.toUInt32.toUInt8))
    return d
  memsetRaw d c n

'''

NEW_STRNCPY = '''/-- (generated) `strncpy` into the bridged range: the bytes C writes, through `wrBlock` -/
def strncpy (d s : UInt64) (n : UInt64) : M UInt64 := do
  if !inBridgeN d n.toNat then
    return (← strncpyRaw d s n)
  let mut bs := ByteArray.empty
  let mut ended := false
  for k in [0:n.toNat] do
    if ended then
      bs := bs.push 0
    else
      let c ← rd (s + k.toUInt64)
      bs := bs.push c
      if c == 0 then ended := true
  wrBlock d bs
  return d

'''

NEW_HALREAD = '''/-- (generated) `halRead` into the bridged range: the storage block through `wrBlock` -/
def halRead (dst : UInt64) (src : UInt16) (n : UInt64) : M Unit := do
  if !inBridgeN dst n.toNat then
    halReadRaw dst src n
    return
  let s ← get
  if src.toNat + n.toNat > s.st.size then return
  wrBlock dst (s.st.extract src.toNat (src.toNat + n.toNat))

'''


def memory():
    src = open(os.path.join(HERE, "ParamMemory.lean")).read()
    t = src
    t = sub1(t, r"^import CFloat\n", "import CFloat\nimport VehicleBridgeMap\n\n" + DOC, re.M)
    # the World inside the memory state
    t = insert_before(t, "\ninstance : Inhabited Mem :=",
                      "  /-- (generated) the estimator's value World inside the memory state, and its output log -/\n"
                      "  w : Estimator_lib.World := Estimator_lib.World.init\n"
                      "  eo : Estimator_lib.Outputs := #[]\n"
                      "  /-- (generated) the vehicle HAL's state (lockstep.cpp's drivers), kept by the replay driver -/\n"
                      "  hx : Array UInt64 := #[]\n"
                      "  hs : Array String := #[]\n"
                      "  hb : Array ByteArray := #[]\n"
                      "  hn : Array (Array UInt64) := #[]\n")
    # the original definitions keep their text under a Raw name; the bridged ones take the original names
    for nm in ("rd", "wr", "ldU16", "ldU32", "stU16", "stU32", "memcpy", "memset", "strncpy", "halRead"):
        t = sub1(t, r"^(@\[inline\] )?def %s \(" % nm, lambda m, nm=nm: "%sdef %sRaw (" % (m.group(1) or "", nm), re.M)
    t = insert_before(t, "@[inline] def ldU8 ", NEW_RD_WR)
    t = insert_before(t, "@[inline] def ldU64 ", NEW_LD + "\n")
    t = insert_before(t, "@[inline] def stU64 ", NEW_ST)
    t = insert_before(t, "def strlen ", NEW_MEM)
    t = insert_before(t, "@[inline] def diff ", NEW_STRNCPY)
    t = insert_before(t, "def halWrite ", NEW_HALREAD)
    # inside the Raw stores, the byte writes stay raw (the bridged test is made once, by the caller)
    def raw_body(t, nm, inner):
        m = re.search(r"^(@\[inline\] )?def %sRaw \(.*?(?=^\S)" % nm, t, re.M | re.S)
        body = m.group(0)
        nb = body
        for a, b in inner:
            nb = re.sub(r"\b%s\b" % a, b, nb)
        return t.replace(body, nb, 1)
    t = raw_body(t, "stU16", [("wr", "wrRaw")])
    t = raw_body(t, "stU32", [("wr", "wrRaw")])
    t = raw_body(t, "memcpy", [("wr", "wrRaw"), ("rd", "rdRaw")])
    t = raw_body(t, "memset", [("wr", "wrRaw")])
    t = raw_body(t, "strncpy", [("wr", "wrRaw"), ("rd", "rdRaw")])
    t = raw_body(t, "halRead", [("wr", "wrRaw")])
    open(os.path.join(HERE, "ParamMemoryV.lean"), "w").write(t)
    for f in ("GCSMemory", "VehicleMemory"):
        s = open(os.path.join(HERE, f + ".lean")).read()
        s = re.sub(r"^import (ParamMemory|GCSMemory)$", r"import \1V", s, flags=re.M)
        s = s.replace("/-!\n", "/-!\nGENERATED by support/gen_param_memory_v.py from support/%s.lean (its imports: the memory with the World\n"
                      "inside, ParamMemoryV). Do not edit.\n\n" % f, 1)
        open(os.path.join(HERE, f + "V.lean"), "w").write(s)
    print("gen_param_memory_v: support/ParamMemoryV.lean, GCSMemoryV.lean, VehicleMemoryV.lean")


def lean_paths(sig):
    """{probe path (est_probe.cpp's `# params` name): (World field name, leaf)}, as estimation_replay.gen_params"""
    leaves = {}
    for w in sig["world"]:
        if w.get("class") is None:
            continue
        c = next(c for c in sig["classes"] if c["cxx"] == w["class"])
        for lf in c["leaves"]:
            leaves["%s.%s" % (w["name"], lf["cxx"])] = (w["name"], lf)
    return leaves


GET = {"float": "(Binary32.toBits {p}).toUInt64", "uint8_t": "({p}).toUInt64", "uint16_t": "({p}).toUInt64",
       "uint32_t": "({p}).toUInt64", "int8_t": "({p}).toUInt8.toUInt64", "int16_t": "({p}).toUInt16.toUInt64",
       "int32_t": "({p}).toUInt32.toUInt64", "bool": "(if {p} then 1 else 0)"}
SET = {"float": "Binary32.ofBits v.toUInt32", "uint8_t": "v.toUInt8", "uint16_t": "v.toUInt16", "uint32_t": "v.toUInt32",
       "int8_t": "v.toUInt8.toInt8", "int16_t": "v.toUInt16.toInt16", "int32_t": "v.toUInt32.toInt32", "bool": "(v &&& 0xff) != 0"}
SIZE = {"float": 4, "uint8_t": 1, "uint16_t": 2, "uint32_t": 4, "int8_t": 1, "int16_t": 2, "int32_t": 4, "bool": 1}


def bridge_map(out_dirs):
    sys.path.insert(0, os.path.join(ROOT, "ardupilot"))
    import sensors_replay as sr
    sig = json.load(open(os.path.join(ROOT, "ardupilot", "out", "Estimator", "Estimator_lib.signatures.json")))
    leaves = lean_paths(sig)
    eps = json.load(open(os.path.join(ROOT, "ardupilot", "out", "Vehicle", "estimator_params.json")))
    rows = []
    for e in eps:
        nm = e["path"]
        obj, _, rest = nm.partition(".")
        m = re.match(r"^(.*)\.([xyz])$", rest)
        cands = ["%s.%s._value" % (obj, rest)] + (["%s.%s._value.%s" % (obj, m.group(1), m.group(2))] if m else []) + ["%s.%s" % (obj, rest)]
        hit = next((leaves[c] for c in cands if c in leaves), None)
        if hit is None:
            sys.exit("gen_param_memory_v: no World leaf for %s" % nm)
        wname, lf = hit
        ty = lf["type"]
        if SIZE.get(ty) != e["size"]:
            sys.exit("gen_param_memory_v: %s: World type %s, clang size %d" % (nm, ty, e["size"]))
        steps = [("f", wname)] + sr.lean_steps(lf["lean"])
        path = "w." + wname + "." + lf["lean"]
        rows.append((e["addr"], e["size"], nm, GET[ty].format(p=path), sr.update_expr("w", steps, SET[ty])))
    rows.sort()
    for (a, n, p, _, _), (b, _, q, _, _) in zip(rows, rows[1:]):
        if a + n > b:
            sys.exit("gen_param_memory_v: fields overlap: %s, %s" % (p, q))
    lo, hi = rows[0][0], rows[-1][0] + rows[-1][1]
    L = ["import Estimator_lib", "",
         "/-!", "GENERATED by support/gen_param_memory_v.py --bridge (do not edit): the bridged fields of the vehicle image",
         "(ardupilot/out/Vehicle/Vehicle_lib.addresses.json; ardupilot/out/Vehicle/estimator_params.json: clang's offsets of the",
         "estimator's %d parameters in `copter` and `AP_AHRS_NavEKF3::EKF3`), each with its World path (the estimator's" % len(rows),
         "signatures). `support/ParamMemoryV.lean` sends every memory access to these bytes to the World field.", "-/", "",
         "open FloatLib.Floats (Binary32 Binary64)", "", "namespace PMem.Bridge", "", "open Estimator_lib", "",
         "/-- the bridged range: no bridged byte lies outside [lo, hi) -/",
         "def lo : UInt64 := 0x%x" % lo, "def hi : UInt64 := 0x%x" % hi, "",
         "/-- the bridged fields by address: (address, size); the probe's name in the comment -/",
         "def fields : Array (UInt64 × Nat) := #["]
    L.append(",\n".join("  (0x%x, %d) /- %s -/" % (a, n, p) for a, n, p, _, _ in rows))
    L += ["]", "",
          "/-- (Phase 5b, speed) each address of [lo, hi): 1 + the index of the field containing it, or 0 (computed once) -/",
          "def slots : Array UInt16 := Id.run do",
          "  let mut t := Array.replicate (hi - lo).toNat (0 : UInt16)",
          "  for i in [0:fields.size] do",
          "    let (b, n) := fields[i]!",
          "    for k in [0:n] do",
          "      t := t.set! ((b - lo).toNat + k) (i + 1).toUInt16",
          "  return t", "",
          "/-- the field containing `a`: (its address, its index), by the slot table (the binary search's answer) -/",
          "def find (a : UInt64) : Option (UInt64 × Nat) :=",
          "  if a < lo || hi ≤ a then none else",
          "  let j := (slots[(a - lo).toNat]!).toNat",
          "  if j == 0 then none else some ((fields[j - 1]!).1, j - 1)", "",
          "def size (i : Nat) : Nat := (fields[i]!).2", "",
          "/-! Each field's getter (its bits, little endian, its size, from the World) and setter (the World with the field",
          "set from its bits). -/", ""]
    for k, (_, _, p, g, st) in enumerate(rows):
        L += ["/-- `%s` -/" % p, "def get'%d (w : World) : UInt64 := %s" % (k, g), "def set'%d (w : World) (v : UInt64) : World := %s" % (k, st), ""]
    L += ["def getters : Array (World → UInt64) := #[" + ", ".join("get'%d" % k for k in range(len(rows))) + "]",
          "def setters : Array (World → UInt64 → World) := #[" + ", ".join("set'%d" % k for k in range(len(rows))) + "]", "",
          "@[inline] def get (w : World) (i : Nat) : UInt64 := (getters[i]?.getD (fun _ => 0)) w",
          "@[inline] def set (w : World) (i : Nat) (v : UInt64) : World := (setters[i]?.getD (fun w _ => w)) w v", "",
          "/-- the probe's names of the fields (diagnosis) -/",
          "def names : Array String := #[" + ", ".join('"%s"' % p for _, _, p, _, _ in rows) + "]", ""]
    # (Phase 5b) a parameter object's address by its C++ path from its World object (the World's `AP_Param_save`
    # events): a scalar parameter is its field, a vector parameter its first component (`ins._gyro_offset_old_param[0]`
    # is `.x`'s address); 0 for a path that is not a bridged parameter
    objs = {}
    for a, n, p, _, _ in rows:
        objs.setdefault(p, a)
        if p.endswith(".x"):
            objs.setdefault(p[:-2], a)
    L += ["/-- a bridged parameter object's address by its C++ path (0: none) -/",
          "def addrOfPath (p : String) : UInt64 :=",
          "  match p with"] + ['  | "%s" => 0x%x' % (p, a) for p, a in sorted(objs.items())] + ["  | _ => 0", "",
          "end PMem.Bridge", ""]
    text = "\n".join(L)
    for d in out_dirs:
        open(os.path.join(d, "VehicleBridgeMap.lean"), "w").write(text)
    print("gen_param_memory_v: VehicleBridgeMap.lean: %d fields in [0x%x, 0x%x)" % (len(rows), lo, hi))


def main():
    if "--memory" in sys.argv:
        memory()
    if "--bridge" in sys.argv:
        bridge_map([os.path.join(ROOT, "ardupilot", "out", "Vehicle"), os.path.join(ROOT, "lean")])


if __name__ == "__main__":
    main()
