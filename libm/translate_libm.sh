#!/usr/bin/env bash
# Translate the C library functions the translated code calls (cpp2lean/README.md, "The C library"):
# musl 1.2.5's C sources (libm/musl-1.2.5, unmodified), one translation unit per function f
# (libm/unity/unity_f.c: f.c and the files of the helpers it calls, libm/unity/groups.txt; after `|`,
# the helpers translated as modules of their own, called through their signatures.json), with
# the environment headers of libm/env and the reference's flags. Output: libm/out/Musl/f.lean, the
# module Musl.f, namespace Musl.f, function Musl.f.f (and Musl.lean, which imports them all).
# Usage: libm/translate_libm.sh [function...]   (default: every function of groups.txt)
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
M="$HERE/musl-1.2.5"
OUT="$HERE/out"
INC=(-I "$HERE/env" -I "$M/src/internal" -I "$M/src/math")
cd "$ROOT"
if [ $# -gt 0 ]; then FNS=("$@"); else FNS=($(cut -d: -f1 "$HERE/unity/groups.txt")); fi
for f in "${FNS[@]}"; do
  line="$(grep "^$f:" "$HERE/unity/groups.txt" | cut -d: -f2)"
  files=(${line%%|*})
  mods=()
  if [[ "$line" == *"|"* ]]; then mods=(${line#*|}); fi
  H=(); C=(); S=()
  for x in "${files[@]}"; do H+=(--header "$M/src/math/$x.c"); C+=("$M/src/math/$x.c"); done
  for x in "${mods[@]+"${mods[@]}"}"; do S+=(--module-sig "$OUT/Musl/$x.signatures.json"); done
  python3 ardupilot/check_unity.py "$HERE/unity/unity_$f.c" "${C[@]}" -- -x c -std=c99 "${INC[@]}" > /dev/null
  python3 cpp2lean.py "$HERE/unity/unity_$f.c" -o "$OUT" --namespace "Musl.$f" "${H[@]}" "${S[@]+"${S[@]}"}" "${INC[@]}" \
    --lib-dir "$M/src/internal" --lib-dir "$M/src/math" --general-loops --uninit-reads --nest \
    --drop fp_force_evalf --drop fp_force_eval --drop fp_force_evall --src-root "$M"
done
# Musl.lean: every function's module
{
  for f in $(cut -d: -f1 "$HERE/unity/groups.txt"); do echo "import Musl.$f"; done
  echo ""
  echo "/-! Generated by libm/translate_libm.sh: the translations of musl's C library functions (cpp2lean/README.md, \"The C library\"). -/"
} > "$OUT/Musl.lean"
rm -f "$OUT"/Musl/*.signatures.json.tmp
