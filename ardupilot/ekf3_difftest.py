def bench(cfg, sig, layout, bdir, exe, lexe, steps):
    """Run both timed drivers on each run's lines; summarize ns per call by kind (C++ and Lean)."""
    import statistics
    for run in cfg["runs"]:
        n = steps or run["steps"]
        lines = ekf3_scenario.lines(run, n, lambda vals: tokens_of(sig, layout, vals))
        base = os.path.join(bdir, run["name"] + "_bench")
        with open(base + ".in", "w") as f:
            f.write("\n".join(lines) + "\n")
        lo = subprocess.run([lexe], stdin=open(base + ".in"), stdout=subprocess.PIPE, check=True).stdout.decode().split("\n")
        co = subprocess.run([exe], stdin=open(base + ".in"), stdout=subprocess.PIPE, check=True).stdout.decode().split("\n")
        rows = []
        for k, (l, c) in enumerate(zip(lo, co)):
            if not l:
                continue
            op, ns, pred, ncores = l.split()
            rows.append((k, op, int(ns), pred == "1", int(ncores), int(c.split()[1])))
        def summ(sel, label):
            r = [x for x in rows if sel(x)]
            if not r:
                return
            ln = [x[2] for x in r]
            cn = [x[5] for x in r]
            print("  %-44s %6d calls  Lean mean %9.0f ns  median %9.0f  p99 %9.0f   C++ mean %7.0f ns  ratio %5.0f" %
                  (label, len(r), statistics.mean(ln), statistics.median(ln), sorted(ln)[int(0.99 * (len(ln) - 1))],
                   statistics.mean(cn), statistics.mean(ln) / max(1.0, statistics.mean(cn))))
        print("ardupilot/EKF3 bench (%s, %d steps):" % (run["name"], n))
        summ(lambda x: x[1] == "U" and x[4] > 0, "UpdateFilter, all steps")
        summ(lambda x: x[1] == "U" and x[4] > 0 and x[3], "UpdateFilter, prediction steps")
        summ(lambda x: x[1] == "U" and x[4] > 0 and not x[3], "UpdateFilter, other steps")
        summ(lambda x: x[1] == "U" and x[4] > 0 and x[0] >= 14000 and x[3], "  prediction steps after GPS aiding (> 35 s)")
        summ(lambda x: x[1] == "U" and x[4] > 0 and x[0] >= 14000 and not x[3], "  other steps after GPS aiding (> 35 s)")
        summ(lambda x: x[1] == "I", "InitialiseFilter")


