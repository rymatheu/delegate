def method(sig, name):
    return next(m for m in cls(sig, "NavEKF3")["methods"] if m["lean"].endswith(".NavEKF3." + name))


def cpp_driver(sig, cfg, layout):
    lines = ["// Generated by ardupilot/ekf3_difftest.py: the C++ side of the NavEKF3 difftest.",
             "#include <cinttypes>", "#include <cstdint>", "#include <cstdio>", "#include <cstdlib>", "#include <cstring>"]
    lines += dt.heap_registry(sig)
    lines += ["void *cpp2lean_raw_alloc(size_t n) { void *p = calloc(1, n); cpp2lean_log(p, n, true); return p; }",
              "#undef malloc", "#include \"ekf3_env.h\"", "#include <AP_NavEKF3/AP_NavEKF3.h>",
              "#include <AP_NavEKF3/AP_NavEKF3_core.h>", "#include <AP_DAL/AP_DAL.h>", "", "NavEKF3 EKF3;", ""]
    lines += dt.heap_names(sig)
    lines += dt.CPP_PRELUDE
    # the dump
    lines.append("static void dump() {")
    for w in sig["world"] + sig.get("world_statics", []):
        if w.get("local"):
            continue
        for lf, cxx, _ in dt.world_leaves(sig, w):
            lines.append("    " + dt.cpp_token_print(lf["type"], cxx, lf["enum"] is not None))
    for hi, h in enumerate(sig.get("heap", [])):
        c = cls(sig, h["class"])
        lines.append("    { int k = 0; for (int i = 0; i < cpp2lean_nalloc; i++) { size_t m; if (cpp2lean_class_of(cpp2lean_allocs[i], &m) == %d) k += (int)m; } printf(\" h:%%d\", k); }" % hi)
        lines.append("    for (int i = 0; i < cpp2lean_nalloc; i++) { size_t m; if (cpp2lean_class_of(cpp2lean_allocs[i], &m) != %d) continue;" % hi)
        lines.append("        for (size_t j = 0; j < m; j++) { %s *o = (%s *)((char *)cpp2lean_allocs[i].p + j * sizeof(%s));" % (h["class"], h["class"], h["class"]))
        for lf in c["leaves"]:
            lines.append("            " + dt.cpp_token_print(lf["type"], "o->" + lf["cxx"], lf["enum"] is not None))
        lines.append("        } }")
    lines += ["    printf(\" o:\"); tu(env_out.baro_update_calibration_calls); tb(env_out.ahrs_set_takeoff_expected);", "}", ""]
    # the inputs
    lines.append("static void set_inputs(char **tok) {")
    k = 0
    for lroot, croot, f, t, n, lvs in layout:
        for j in range(n or 1):
            for lean, cxx, lt, en in lvs:
                tgt = "%s.%s%s%s" % (croot, f, "[%d]" % j if n else "", cxx)
                if en is not None:
                    e = next(e for e in sig["enums"] if e["lean"] == en)
                    lines.append("    %s = static_cast<%s>(strtoll(tok[%d], nullptr, 10));" % (tgt, e["cxx"], k))
                else:
                    lines.append("    %s = %s;" % (tgt, dt.cpp_read(lt, "tok[%d]" % k)))
                k += 1
    lines += ["}", ""]
    nin = k
    # the sources (AP_NavEKF_Source, --boundary-call): the line's values must be what the real functions return
    lines.append("static void check_sources() {")
    for lroot, croot, f, t, n, lvs in layout:
        if croot not in ("env_ekf3", "env_core"):
            continue
        call = cfg["source_calls"].get(f)
        if call is None:
            lines.append("    // %s: no check configured" % f)
            continue
        for j in range(n or 1):
            lines.append("    if (!(EKF3.sources.%s == %s.%s%s)) { fprintf(stderr, \"source input %s[%d] differs from AP_NavEKF_Source\\n\"); exit(6); }" %
                         (call.replace("$i", str(j)), croot, f, "[%d]" % j if n else "", f, j))
    lines += ["}", ""]
    # the getters
    lines.append("static void getters() {")
    for g in cfg["getters"]:
        m = method(sig, g["name"])
        args = []
        for i, p in enumerate(m["params"]):
            if p["ref"] == "mut":
                ct = cfg.get("cxx_param_types", {}).get("%s.%s" % (g["name"], p["name"]), [p["type"], ""])[0]
                lines.append("    %s a%d_%s{}; memset((void *)&a%d_%s, 0, sizeof(a%d_%s));" % ("Quaternion" if p["type"] == "QuaternionT<float>" else ct, i, g["name"], i, g["name"], i, g["name"]))
                args.append("a%d_%s" % (i, g["name"]))
            else:
                args.append(str(g["args"][p["name"]]))
        call = "EKF3.%s(%s)" % (g["name"], ", ".join(args))
        if m["ret"] == "void":
            lines.append("    %s;" % call)
        else:
            lines.append("    { auto r = %s; %s }" % (call, " ".join(dt.cpp_token_print(lt, "r" + cx, en is not None) for _, cx, lt, en in leaves_of(sig, m["ret"]))))
        for i, p in enumerate(m["params"]):
            if p["ref"] == "mut":
                sfx = cfg.get("cxx_param_types", {}).get("%s.%s" % (g["name"], p["name"]), [p["type"], ""])[1]
                for _, cx, lt, en in leaves_of(sig, p["type"]):
                    lines.append("    " + dt.cpp_token_print(lt, "a%d_%s%s%s" % (i, g["name"], sfx, cx), en is not None))
    lines += ["}", ""]
    lines += ["int main() {", "    static char buf[1 << 20];", "    long line = 0;",
              "    printf(\"0 init |\"); dump(); printf(\"\\n\");",
              "    while (fgets(buf, sizeof buf, stdin)) {", "        line++;", "        static char *tok[1 << 14];", "        int nt = 0;",
              "        for (char *p = strtok(buf, \" \\n\"); p && nt < (1 << 14); p = strtok(nullptr, \" \\n\")) tok[nt++] = p;",
              "        if (nt != %d) { fprintf(stderr, \"bad input line %%ld (%%d tokens)\\n\", line, nt); return 1; }" % (nin + 1),
              "        set_inputs(tok + 1);", "        ekf3_env_apply();",
              "        printf(\"%ld %s\", line, tok[0]);",
              "        if (!strcmp(tok[0], \"I\")) { tb(EKF3.InitialiseFilter()); }",
              "        else if (!strcmp(tok[0], \"U\")) { EKF3.UpdateFilter(); }",
              "        else if (!strcmp(tok[0], \"A\")) {   // as AP_AHRS::update_EKF3: initialise until it succeeds, then update",
              "            static bool started;",
              "            if (!started) { bool r = EKF3.InitialiseFilter(); printf(\" init\"); tb(r); started = r; } else { printf(\" update\"); EKF3.UpdateFilter(); }",
              "        }",
              "        else { printf(\" ?\"); }", "        check_sources();", "        getters();",
              "        printf(\" |\"); dump(); printf(\"\\n\");", "    }", "    return 0;", "}", ""]
    return "\n".join(lines), nin


def lean_call(sig, m, extra_args, outs_name):
    """(lines, result tokens) of a call of NavEKF3 member function m on the World `w` (rebinding w)."""
    args = []
    if "p" in m["reads"] + m["writes"]:
        args.append("w.EKF3'p")
    if "s" in m["reads"] + m["writes"]:
        args.append("w.EKF3")
    if "w" in m["reads"] + m["writes"]:
        args.append("w")
    if m["uses_inp"]:
        args.append("w.EKF3'inp")
    args += extra_args
    comps = [c for c in ("p", "s", "w") if c in m["writes"]]
    outs = [i for i, p in enumerate(m["params"]) if p["ref"] == "mut"]
    comps += ["o%d" % i for i in outs]
    if m["ret"] != "void":
        comps.append("r")
    names = ["%s_%d" % (outs_name, i) for i in range(len(comps))]
    lines = []
    call = "NavEKF3.%s %s" % (m["lean"].split(".")[-1], " ".join(args))
    if comps:
        lines.append("  let %s := %s" % (names[0] if len(comps) == 1 else "(%s)" % ", ".join(names), call))
    for c, nm in sorted(zip(comps, names), key=lambda x: 0 if x[0] == "w" else 1):
        if c == "w":
            lines.append("  let w := %s" % nm)
        elif c == "p":
            lines.append("  let w := { w with EKF3'p := %s }" % nm)
        elif c == "s":
            lines.append("  let w := { w with EKF3 := %s }" % nm)
    toks = []
    if m["ret"] != "void":
        toks += [dt.lean_tok(lt, names[comps.index("r")] + ln, en) for ln, _, lt, en in leaves_of(sig, m["ret"])]
    for i in outs:
        p = m["params"][i]
        toks += [dt.lean_tok(lt, names[comps.index("o%d" % i)] + ln, en) for ln, _, lt, en in leaves_of(sig, p["type"])]
    return lines, toks


def lean_value(sig, lt, tok, en):
    if en is not None:
        return "%s.ofInt'' (inInt %s)" % (en, tok)
    return dt.lean_in(lt, tok)


def lean_driver(sig, cfg, layout, nin):
    ns = sig["namespace"]
    out = ["-- Generated by ardupilot/ekf3_difftest.py: the Lean side of the NavEKF3 difftest.",
           "import %s" % ns, "", "open FloatLib.Floats (Binary32 Binary64)", "open %s" % ns, "",
           "set_option maxRecDepth 200000", "",
           "def hexNat (s : String) : Nat :=",
           "  s.foldl (fun acc c => acc * 16 + (if c.isDigit then c.toNat - '0'.toNat else c.toLower.toNat - 'a'.toNat + 10)) 0",
           "def hex (width : Nat) (n : Nat) : String :=",
           "  let d := String.ofList (Nat.toDigits 16 n)",
           "  String.ofList (List.replicate (width - d.length) '0') ++ d",
           "def inF32 (s : String) : Binary32 :=",
           "  let u := (hexNat s).toUInt32",
           "  Binary32.ofBits (if u &&& 0x7f800000 == 0x7f800000 && u &&& 0x7fffff != 0 then u ||| 0x400000 else u)",
           "def inF64 (s : String) : Binary64 :=",
           "  let u := (hexNat s).toUInt64",
           "  Binary64.ofBits (if u &&& 0x7ff0000000000000 == 0x7ff0000000000000 && u &&& 0xfffffffffffff != 0 then u ||| 0x8000000000000 else u)",
           "def inInt (s : String) : Int := (s.toInt?).getD 0",
           "def inNat (s : String) : Nat := (s.toNat?).getD 0",
           "def tF32 (x : Binary32) : String := \" f:\" ++ hex 8 (Binary32.toBits x).toNat",
           "def tF64 (x : Binary64) : String := \" d:\" ++ hex 16 (Binary64.toBits x).toNat",
           "def tB (b : Bool) : String := if b then \" b:1\" else \" b:0\"",
           "def tI (x : String) : String := \" i:\" ++ x",
           "def tP (x : String) : String := \" p:\" ++ x", ""]
    # enum readers: the enumerator with the value read
    used = sorted({en for _, _, _, _, _, lvs in layout for _, _, _, en in lvs if en})
    for en in used:
        e = next(e for e in sig["enums"] if e["lean"] == en)
        out.append("def %s.ofInt'' (v : Int) : %s :=" % (en, en))
        for i, (nm, v, ln) in enumerate(e["values"]):
            out.append("  %sif v == %d then %s.%s" % ("" if i == 0 else "else ", v, en, ln))
        out.append("  else default")
    out.append("")
    # inputs: one definition per record (Lean elaborates long records slowly)
    k = 0
    recs = {}
    order = []
    for lroot, croot, f, t, n, lvs in layout:
        vals = []
        for j in range(n or 1):
            if len(lvs) == 1 and lvs[0][0] == "":
                lt, en = lvs[0][2], lvs[0][3]
                vals.append(lean_value(sig, lt, "t[%d]!" % (k + 1), en))
                k += 1
            else:
                fields = []
                for lean, cxx, lt, en in lvs:
                    fields.append((lean.strip("."), lean_value(sig, lt, "t[%d]!" % (k + 1), en)))
                    k += 1
                vals.append(nest_record(fields))
        v = "#[%s]" % ", ".join(vals) if n else vals[0]
        if lroot not in recs:
            recs[lroot] = []
            order.append(lroot)
        recs[lroot].append((f, v))
    assert k == nin
    W = "World"
    out.append("def setInputs (w : %s) (t : Array String) : %s :=" % (W, W))
    # nested Inputs records: build the innermost first
    for lroot in sorted(order, key=lambda r: -r.count(".")):
        pass
    for lroot in order:
        parent = lroot
        out.append("  let w := { w with %s := { %s with %s } }" % (lroot[2:], lroot, ", ".join("%s := %s" % (f, v) for f, v in recs[lroot])))
    out.append("  w")
    out.append("")
    # the dump, in chunks
    toks = []
    for w in sig["world"] + sig.get("world_statics", []):
        if w.get("local"):
            continue
        toks += [dt.lean_tok(lf["type"], lean, lf["enum"]) for lf, _, lean in dt.world_leaves(sig, w)]
    chunks = [toks[i:i + 150] for i in range(0, len(toks), 150)]
    for ci, ch in enumerate(chunks):
        out.append("def dumpW_%d (w : %s) : String :=" % (ci, W))
        out.append("  \"\"" + "".join(" ++ " + t for t in ch))
        out.append("")
    hparts = []
    for hi, h in enumerate(sig.get("heap", [])):
        c = cls(sig, h["class"])
        ltoks = [dt.lean_tok(lf["type"], "st.%s" % lf["lean"], lf["enum"]) for lf in c["leaves"]]
        hch = [ltoks[i:i + 150] for i in range(0, len(ltoks), 150)] or [[]]
        for ci, ch in enumerate(hch):
            out.append("def dumpH_%d_%d (st : %s.State) : String :=" % (hi, ci, h["lean"]))
            out.append("  \"\"" + "".join(" ++ " + t for t in ch))
            out.append("")
        out.append("def dumpH_%d (w : %s) : String :=" % (hi, W))
        out.append("  \" h:\" ++ toString w.%s.size ++ w.%s.foldl (fun acc st => acc%s) \"\"" %
                   (h["field"], h["field"], "".join(" ++ dumpH_%d_%d st" % (hi, ci) for ci in range(len(hch)))))
        out.append("")
        hparts.append("dumpH_%d w" % hi)
    out.append("def dump (w : %s) : String :=" % W)
    out.append("  " + " ++ ".join(["dumpW_%d w" % ci for ci in range(len(chunks))] + hparts +
                                  ["\" o:\"", "tI (toString w.heap'AP_DAL'o._baro.update_calibration_calls)", "tB w.heap'AP_DAL'o.set_takeoff_expected"]))
    out.append("")
    # the getters
    out.append("def getters (w : %s) : %s × String := Id.run do" % (W, W))
    gtoks = []
    for gi, g in enumerate(cfg["getters"]):
        m = method(sig, g["name"])
        extra = []
        for i, p in enumerate(m["params"]):
            if p["ref"] == "mut":
                extra.append("{}" if p["type"] not in dt.INTS and p["type"] not in ("float", "double", "bool") else ("(0 : %s)" % dt.lean_type(p["type"]) if p["type"] != "bool" else "false"))
                if p["type"] in ("float", "double"):
                    extra[-1] = "(%s.ofBits 0)" % dt.lean_type(p["type"])
            else:
                extra.append("(%s : %s)" % (g["args"][p["name"]], dt.lean_type(p["type"])))
        ls, tk = lean_call(sig, m, extra, "g%d" % gi)
        out += ls
        out.append("  let s%d : String := %s" % (gi, " ++ ".join(["\"\""] + tk)))
        gtoks.append("s%d" % gi)
    out.append("  return (w, %s)" % " ++ ".join(["\"\""] + gtoks))
    out.append("")
    init = method(sig, "InitialiseFilter")
    upd = method(sig, "UpdateFilter")
    il, itoks = lean_call(sig, init, [], "i")
    ul, _ = lean_call(sig, upd, [], "u")
    out.append("def callInit (w : %s) : %s × String := Id.run do" % (W, W))
    out += il + ["  return (w, %s)" % " ++ ".join(["\"\""] + itoks), ""]
    out.append("def callUpdate (w : %s) : %s := Id.run do" % (W, W))
    out += ul + ["  return w", ""]
    out += ["partial def loop (h : IO.FS.Stream) (o : IO.FS.Stream) (w : %s) (n : Nat) (started : Bool) : IO Unit := do" % W,
            "  let line ← h.getLine", "  if line.isEmpty then return",
            "  let t := (((line.trimAscii.toString).splitOn \" \").filter (· ≠ \"\")).toArray",
            "  let w := setInputs w t",
            "  -- `A`: as AP_AHRS::update_EKF3, InitialiseFilter until it succeeds, then UpdateFilter",
            "  let (w, r, started) := if t[0]! == \"I\" then (let (w, r) := callInit w; (w, r, started))",
            "    else if t[0]! == \"U\" then (callUpdate w, \"\", started)",
            "    else if t[0]! == \"A\" then (if started then (callUpdate w, \" update\", started) else",
            "      (let (w, r) := callInit w; (w, \" init\" ++ r, r == \" b:1\")))",
            "    else (w, \" ?\", started)",
            "  let (w, g) := getters w",
            "  o.putStr (toString (n + 1) ++ \" \" ++ t[0]! ++ r ++ g ++ \" |\" ++ dump w ++ \"\\n\")",
            "  o.flush",
            "  loop h o w (n + 1) started", "",
            "def main : IO Unit := do",
            "  let w := World.init",
            "  let o ← IO.getStdout",
            "  o.putStr (\"0 init |\" ++ dump w ++ \"\\n\")",
            "  loop (← IO.getStdin) o w 0 false", ""]
    return "\n".join(out)


def lean_bench(sig, cfg, layout, nin):
    """The speed measurement (`--bench`, README.md "Phase 3: AP_DAL and NavEKF3"): the lines' inputs are set as
    in the difftest, and only the front end's call is timed (IO.monoNanosNow around a call whose result is
    forced); per line `<op> <ns> <predicted>` (predicted: the primary core ran its prediction step,
    `framesSincePredict` is 0 after the call), no dump."""
    text = lean_driver(sig, cfg, layout, nin)
    head = text[:text.index("partial def loop")]
    out = [head,
           "def predicted (w : World) : Bool :=",
           "  match w.heap'NavEKF3_core[0]? with",
           "  | some c => c.framesSincePredict == 0",
           "  | none => false", "",
           "partial def bench (h : IO.FS.Stream) (o : IO.FS.Stream) (w : World) (started : Bool) : IO Unit := do",
           "  let line ← h.getLine", "  if line.isEmpty then return",
           "  let t := (((line.trimAscii.toString).splitOn \" \").filter (· ≠ \"\")).toArray",
           "  let w := setInputs w t",
           "  let w ← pure w",
           "  let t0 ← IO.monoNanosNow",
           "  let (w, started) := if started || t[0]! == \"U\" then (callUpdate w, started) else",
           "      (let (w, r) := callInit w; (w, r == \" b:1\"))",
           "  -- force the call before the clock is read again",
           "  let p := predicted w",
           "  let n := w.heap'NavEKF3_core.size",
           "  let t1 ← IO.monoNanosNow",
           "  o.putStr (s!\"{if started || t[0]! == \"U\" then \"U\" else \"I\"} {t1 - t0} {if p then 1 else 0} {n}\\n\")",
           "  bench h o w started", "",
           "def main : IO Unit := do",
           "  let o ← IO.getStdout",
           "  bench (← IO.getStdin) o World.init false", ""]
    return "\n".join(out)


def cpp_bench(drv):
    """The C++ side of `--bench`: the driver's main replaced by a timed loop of the same calls."""
    head = drv[:drv.index("int main() {")]
    return head + "\n".join([
        "#include <chrono>",
        "int main() {", "    static char buf[1 << 20];", "    bool started = false;",
        "    while (fgets(buf, sizeof buf, stdin)) {", "        static char *tok[1 << 14];", "        int nt = 0;",
        "        for (char *p = strtok(buf, \" \\n\"); p && nt < (1 << 14); p = strtok(nullptr, \" \\n\")) tok[nt++] = p;",
        "        set_inputs(tok + 1);", "        ekf3_env_apply();",
        "        auto t0 = std::chrono::steady_clock::now();",
        "        if (started || !strcmp(tok[0], \"U\")) EKF3.UpdateFilter(); else started = EKF3.InitialiseFilter();",
        "        auto t1 = std::chrono::steady_clock::now();",
        "        printf(\"%s %lld\\n\", started ? \"U\" : \"I\", (long long)std::chrono::duration_cast<std::chrono::nanoseconds>(t1 - t0).count());",
        "    }", "    return 0;", "}", ""])


def nest_record(fields):
    """`{ a := x, b := { c := y } }` from dotted field paths."""
    tree = {}
    order = []
    for path, v in fields:
        parts = path.split(".")
        node = tree
        for p in parts[:-1]:
            if p not in node:
                node[p] = {}
            node = node[p]
        node[parts[-1]] = v
    def render(node):
        return "{ %s }" % ", ".join("%s := %s" % (k, render(v) if isinstance(v, dict) else v) for k, v in node.items())
    return render(tree)


