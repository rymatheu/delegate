#!/usr/bin/env python3
"""Differential test of the NavEKF3 translation (README.md, "Phase 3: AP_DAL and NavEKF3").

`python3 difftest.py ardupilot/EKF3` runs this harness (config ardupilot/EKF3.json, "harness"). Both sides
hold the objects as the vehicle has them: the NavEKF3 front end `EKF3` (a file-scope object), AP_DAL the heap
singleton it reaches through `AP::dal()`, the cores in AP_DAL::malloc_type memory, each core's EKFGSF_yaw.
Each input line is one call of the front end, `I` (InitialiseFilter) or `U` (UpdateFilter), after the
boundary has been given the values of the line: every input of the translation (the front ends' getters
as AP_DAL reads them, the source selection of AP_NavEKF_Source, --boundary-call). The C++ side compiles
the unmodified ArduPilot sources with the reference build's flags and answers each getter from the line
(ardupilot/ekf3_env.cpp); the Lean side sets the inputs `w.heap'AP_DAL'inp`, `w.EKF3'inp`,
`w.heap'NavEKF3_core'inp` from it. After each call both print the call's result, the results of the
getters AP_AHRS reads (config "getters"), the outputs to the boundary, and every leaf of every object
(the front end, AP_DAL, every core, every EKFGSF_yaw, the shared statics). The lines come from a scenario
of physically plausible sensor samples (ardupilot/ekf3_scenario.py)."""

