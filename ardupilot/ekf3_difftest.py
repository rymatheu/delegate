N = 3   # the length of every instance-indexed input array (INS_MAX_INSTANCES, BARO/COMPASS/GPS_MAX_INSTANCES, MAX_EKF_CORES)


def cls(sig, cxx):
    return next(c for c in sig["classes"] if c["cxx"] == cxx)


def enum_values(sig, cxx):
    """Name -> value of a translated enum, by its C++ name."""
    e = next((e for e in sig["enums"] if e["cxx"] == cxx), None)
    return e


def leaves_of(sig, ctype):
    """The scalar leaves (lean, cxx, type, enum) of a value of C++ type ctype."""
    if ctype in dt.INTS or ctype in ("float", "double", "bool"):
        return [("", "", ctype, None)]
    e = next((e for e in sig["enums"] if e["cxx"] == ctype), None)
    if e is not None:
        return [("", "", e["under"], e["lean"])]
    c = cls(sig, ctype)
    return [("." + lf["lean"], "." + lf["cxx"], lf["type"], lf.get("enum")) for lf in c["leaves"]]


def input_layout(sig):
    """The inputs of the translation in line order: (Lean record path, C++ struct path, field, C++ type,
    array length or None, leaves)."""
    out = []

    def add(cxx_class, lean_root, cxx_root):
        c = cls(sig, cxx_class)
        for i in c["inputs"]:
            t = i["type"]
            n = None
            if t.endswith("[0]"):
                t, n = t[:-3], N
            out.append((lean_root, cxx_root, i["lean"], t, n, leaves_of(sig, t)))
        for s in c.get("sub_inputs", []):
            add(s["class"], lean_root + "." + s["field"], cxx_root + "." + s["field"])
    add("AP_DAL", "w.heap'AP_DAL'inp", "env_dal")
    add("NavEKF3", "w.EKF3'inp", "env_ekf3")
    add("NavEKF3_core", "w.heap'NavEKF3_core'inp", "env_core")
    return out


def cxx_type(sig, t):
    e = next((e for e in sig["enums"] if e["cxx"] == t), None)
    return t if e is None else t


def struct_name(croot):
    top = {"env_dal": "AP_DAL", "env_ekf3": "NavEKF3", "env_core": "NavEKF3_core"}
    parts = croot.split(".")
    return "cpp2lean_inp_" + "_".join([top[parts[0]]] + parts[1:])


def env_header(sig, layout):
    """ekf3_env.h: the C++ structs holding the inputs of a line, named as the Lean Inputs."""
    structs, order = {}, []
    for lroot, croot, f, t, n, _ in layout:
        if croot not in structs:
            structs[croot] = []
            order.append(croot)
        structs[croot].append("    %s %s%s;" % (t, f, "[%d]" % n if n else ""))
    lines = ["// Generated by ardupilot/ekf3_difftest.py: the boundary inputs of a difftest line (C++ side), one field",
             "// per input of the NavEKF3 translation with its Lean name.", "#pragma once",
             "#include <AP_NavEKF3/AP_NavEKF3.h>", "#include <AP_GPS/AP_GPS.h>", "#include <AP_Common/Location.h>", ""]
    for croot in sorted(order, key=lambda r: -r.count(".")):     # members before their holders
        subs = [k for k in order if k.startswith(croot + ".") and k.count(".") == croot.count(".") + 1]
        lines += ["struct %s {" % struct_name(croot)] + structs[croot] + \
                 ["    %s %s;" % (struct_name(k), k.split(".")[-1]) for k in subs] + ["};", ""]
    lines += ["struct cpp2lean_out_env { uint32_t baro_update_calibration_calls; bool ahrs_set_takeoff_expected; uint32_t ahrs_set_takeoff_expected_calls; };",
              "extern cpp2lean_inp_AP_DAL env_dal;", "extern cpp2lean_inp_NavEKF3 env_ekf3;", "extern cpp2lean_inp_NavEKF3_core env_core;",
              "extern cpp2lean_out_env env_out;", "void *cpp2lean_raw_alloc(size_t n);", "void ekf3_env_apply();", ""]
    return "\n".join(lines)


def tokens_of(sig, layout, vals):
    """The line tokens of the inputs (vals: field path -> value or list of values)."""
    toks = []
    for lroot, croot, f, t, n, lvs in layout:
        key = croot + "." + f
        v = vals.get(key)
        m = re.match(r"^(useVel(XY|Z)Source)_(\w+)_at1$", f)
        if key not in vals and m:
            # useVelXYSource(SourceXY::X, i): the scenario's answer for that source
            e = next(e for e in sig["enums"] if e["cxx"] == "AP_NavEKF_Source::Source" + m.group(2))
            v = vals["@" + m.group(1)](next(x for nm, x, _ in e["values"] if nm == m.group(3)))
        elif key not in vals:
            raise SystemExit("ekf3_difftest: the scenario gives no value for input %s" % key)
        items = v if n else [v]
        if n:
            items = list(items or []) + [None] * (n - len(items or []))
        for it in items:
            for lean, cxx, lt, en in lvs:
                x = it
                if lean and x is not None:
                    for part in cxx.strip(".").split("."):
                        x = x.get(part) if isinstance(x, dict) else None
                toks.append(fmt(lt, x, en))
    return toks


def fmt(t, x, en):
    if x is None:
        x = 0
    if t == "float":
        return "%08x" % struct.unpack(">I", struct.pack(">f", x))[0]
    if t == "double":
        return "%016x" % struct.unpack(">Q", struct.pack(">d", x))[0]
    if t == "bool":
        return "1" if x else "0"
    return str(int(x))


