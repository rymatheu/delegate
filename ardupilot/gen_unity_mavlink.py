class Msg:
    def __init__(self, name):
        self.name = name
        self.low = name.lower()
        fs = [f for f in glob.glob(os.path.join(MAV, "*", "mavlink_msg_%s.h" % self.low)) if "/test/" not in f]
        self.path = fs[0]
        t = open(self.path).read()
        st = re.search(r"typedef struct __mavlink_%s_t \{(.*?)\}\)? mavlink_%s_t;" % (self.low, self.low), t, re.S).group(1)
        self.fields = [(ty, nm, int(n) if n else 0) for ty, nm, n in re.findall(r"^\s*(\w+) (\w+)(?:\[(\d+)\])?;", st, re.M)]
        self.flen = {nm: n for _, nm, n in self.fields}
        m = re.search(r"mavlink_msg_%s_pack\(uint32_t system_id, uint8_t component_id, mavlink_message_t\* msg,\s*(.*?)\)\s*\{" % self.low, t, re.S)
        self.params = []
        for p in m.group(1).split(","):
            p = " ".join(p.split())
            mm = re.match(r"^(const )?(\w+) (\*)?(\w+)$", p)
            ty, ptr, nm = mm.group(2), mm.group(3), mm.group(4)
            self.params.append((ty, nm, self.flen.get(nm, 0) if ptr else 0))
        self.getters = []
        for ret, f, at, an in re.findall(r"static inline (\w+) mavlink_msg_%s_get_(\w+)\(const mavlink_message_t\* msg(?:, (\w+) \*(\w+))?\)" % self.low, t):
            self.getters.append((ret, f, at, self.flen.get(f, 0) if at else 0))
        self.min_len = int(re.search(r"#define MAVLINK_MSG_ID_%s_MIN_LEN (\d+)" % name, t).group(1))
        self.length = int(re.search(r"#define MAVLINK_MSG_ID_%s_LEN (\d+)" % name, t).group(1))

    def decls(self, ind="    "):
        """Local variables with random values for the pack/send parameters."""
        out = []
        for ty, nm, n in self.params:
            # (a quarter of the fields zero: MAVLink 2 trims the payload's trailing zeros, down to one byte)
            if n:
                out.append("%s%s %s[%d];" % (ind, ty, nm, n))
                out.append("%sconst bool %s_zero = rnd(s) %% 4 == 0;" % (ind, nm))
                out.append("%sfor (uint16_t i = 0; i < %d; i++) {" % (ind, n))
                out.append("%s    %s[i] = %s_zero ? (%s)0 : %s;" % (ind, nm, nm, ty, GEN[ty] if ty != "char" else "gen_char(s)"))
                out.append("%s}" % ind)
            elif nm == "target_system":
                out.append("%sconst uint32_t %s = rnd(s) %% 4 == 0 ? 0 : gen_sysid(s);" % (ind, nm))
            else:
                out.append("%sconst %s %s = rnd(s) %% 4 == 0 ? (%s)0 : %s;" % (ind, ty, nm, ty, GEN[ty]))
        return out

    def args(self):
        return ", ".join(nm for _, nm, _ in self.params)

    def fill_struct(self, var, ind="    "):
        """`mavlink_<m>_t var` zeroed, then its fields from the parameters."""
        out = ["%smavlink_%s_t %s;" % (ind, self.low, var), "%smemset(&%s, 0, sizeof(%s));" % (ind, var, var)]
        for ty, nm, n in self.params:
            if n:
                out.append("%sfor (uint16_t i = 0; i < %d; i++) {" % (ind, n))
                out.append("%s    %s.%s[i] = %s[i];" % (ind, var, nm, nm))
                out.append("%s}" % ind)
            elif nm == "target_system":
                out.append("%s%s.%s = (uint8_t)%s;" % (ind, var, nm, nm))
            else:
                out.append("%s%s.%s = %s;" % (ind, var, nm, nm))
        return out


