"""Write ardupilot/unity_mavlink.cpp: the unity translation unit of the MAVLink C library (README.md,
"Phase 4: the MAVLink C library").

The unity includes ArduPilot's GCS_MAVLink.h and the generated mavlink_helpers.h exactly as
GCS_MAVLink.cpp does (ArduPilot's MAVLink fork, dialect `all`, generated by the reference build), so
the helpers (CRC, finalize/send, the parser) and the inline message functions are the reference
build's. It defines what GCS_MAVLink.cpp and GCS_MAVLINK provide around them, as stand-ins (no protocol
code): the per-channel parse buffers and status (`mavlink_get_channel_buffer/status`, GCS_MAVLINK's
`_channel_buffer`/`_channel_status` of the link on that channel), `mavlink_system` (GCS_MAVLink.cpp:
`{7,1}`), and `comm_send_buffer` as a byte queue (the UART a later translation of GCS_MAVLink.cpp
writes to). Then the test functions the difftest drives (ardupilot/Mavlink.json), generated from the
headers for each message of MESSAGES:

- pk_<m>(seed, mode): random fields (strings with zeros anywhere, NaN/inf/denormal/-0 floats, 32-bit
  system and target ids), `_pack`, `_pack_chan`, `_encode` or `_encode_chan` (mode >> 1), MAVLink 1 or 2
  (mode & 1, the channel's OUT_MAVLINK1 flag), then `mavlink_msg_to_send_buffer`;
- sd_<m>(seed, mode): `_send` or `_send_struct` through a channel (bytes written, channel status);
- dc_<m>(seed, len, flags): `_decode` and every getter on a message with random payload bytes, a
  random length (truncated or not), random incompat flags (TARGET32) and target;
- ps_stream(seed, nbytes, mode): the parser (`mavlink_parse_char` or `mavlink_frame_char`, mode & 1)
  fed a random stream of valid MAVLink 1/2 frames of many messages, signed frames (with good and bad
  CRC), corrupted, truncated frames, unknown ids, random incompat flags and garbage;
- crc_buf, msg_entry: the CRC functions and the message table lookup.

Each returns a 64-bit FNV-1a hash of everything it observed: every byte written, every field of the
messages and status structures (for the parser: after every byte).
Usage: python3 ardupilot/gen_unity_mavlink.py  (writes ardupilot/unity_mavlink.cpp)
"""
