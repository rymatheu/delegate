#!/usr/bin/env python3
"""Generate lean/VehicleParams.lean: the Lean vehicle's parameters by ArduPilot name.

The tables are the classes' own AP_Param var_info tables, as the translations recorded them in
their signatures.json (`var_info`: per class, the entries in table order, a parameter with its Lean
path in the class's Params, or a nested table of a member object). The roots and prefixes are those
of ArduCopter/Parameters.cpp (`ATC_` attitude_control :384, `PSC` pos_control :388, `MOT_` motors :460,
`WP_` wp_nav :370), in the order in which ardupilot/vehicle/copter_ref.cpp collects them, so that the
two vehicles list, read and set the same parameters in the same order.

Reading converts the stored value to float, as AP_Param's get() into a float; setting converts the
float as AP_Param::set_value (AP_Param.cpp:1501-1519): a float parameter stores it, an integer one
converts it to its storage type (C++ float-to-integer conversion, truncation toward zero; Lean's
CFloat's Binary32.toIntN agree on every value in range), an enum parameter stores that integer as the enum.

Usage: python3 ardupilot/vehicle/gen_params.py ardupilot/out > lean/VehicleParams.lean
"""
import json
import os
import sys

ROOTS = [  # (prefix, translation, class, World field)
    ("ATC_", "Copter/Copter_lib", "AC_AttitudeControl_Multi", "atc"),
    ("PSC", "Copter/Copter_lib", "AC_PosControl", "psc"),
    ("MOT_", "Copter/Copter_lib", "AP_MotorsMatrix", "mot"),
    ("WP_", "Copter/Copter_lib", "AC_WPNav", "wp"),
]
# the class whose var_info a class uses when it declares none of its own (AP_MotorsMatrix::var_info
# names AP_MotorsMulticopter's, the base class's static member)
INHERITED = {"AP_MotorsMatrix": "AP_MotorsMulticopter"}
INTS = {"int8_t": ("Int8", None), "int16_t": ("Int16", None), "int32_t": ("Int32", None),
        "uint16_t": ("Int16", "UInt16"), "uint8_t": ("Int8", "UInt8")}


def entries(var_info, cls, prefix, path):
    """(name, Lean path in the root's Params, entry) for every parameter reachable from cls's table."""
    table = var_info.get(cls) or var_info.get(INHERITED.get(cls, ""))
    if table is None:
        raise SystemExit("gen_params.py: no var_info table for %s" % cls)
    out = []
    for e in table:
        if "group" in e:
            sub = path + ([e["member"]] if e["member"] else [])
            out += entries(var_info, e["group"], prefix + e["name"], sub)
        else:
            out.append((prefix + e["name"], ".".join(path + [e["param"]]), e))
    return out


def getter(e, x):
    t = e["type"]
    if t == "float":
        return x
    if e["enum"]:
        store, _ = INTS[e["storage"]]
        under = "UInt8"     # the enum's underlying type (AP_Motors::PWMType : uint8_t)
        return "%s.toBinary32 (%s.to%s (%s.toInt %s))" % (store, under, store, e["enum"], x)
    store, field = INTS[t]
    if field:
        return "%s.toBinary32 (%s.to%s %s)" % (store, field, store, x)
    return "%s.toBinary32 %s" % (store, x)


def setter(e, v):
    t = e["type"]
    if t == "float":
        return v
    if e["enum"]:
        store, _ = INTS[e["storage"]]
        return "%s.ofInt (%s.toUInt8 (Binary32.to%s %s))" % (e["enum"], store, store, v)
    store, field = INTS[t]
    if field:
        return "%s.to%s (Binary32.to%s %s)" % (store, field, store, v)
    return "Binary32.to%s %s" % (store, v)


def main():
    out_dir = sys.argv[1]
    lines = ["/-!",
             "Generated by ardupilot/vehicle/gen_params.py from the translations' signatures.json; do not edit.",
             "The vehicle's parameters by ArduPilot name, through the classes' var_info tables (prefixes of",
             "ArduCopter/Parameters.cpp), in the order of ardupilot/vehicle/copter_ref.cpp's `collect_params`.",
             "-/",
             ""]
    imports = []
    allp = []
    for prefix, tr, cls, field in ROOTS:
        sig = json.load(open(os.path.join(out_dir, tr + ".signatures.json")))
        ns = sig["namespace"]
        imports.append(ns)
        for name, path, e in entries(sig["var_info"], cls, prefix, []):
            allp.append((name, field, path, e, ns))
    lines = ["import %s" % ns for ns in dict.fromkeys(imports)] + [""] + lines
    lines += ["open FloatLib.Floats (Binary32 Binary64)", "", "namespace VehicleParams", "",
              "/-- The parameter records of the four classes. -/",
              "structure All where"]
    for prefix, tr, cls, field in ROOTS:
        ns = json.load(open(os.path.join(out_dir, tr + ".signatures.json")))["namespace"]
        lines.append("  %s : %s.%s.Params" % (field, ns, cls))
    lines += ["", "/-- Every parameter name, in table order. -/", "def names : Array String := #["]
    lines.append(",\n".join("  \"%s\"" % n for n, _, _, _, _ in allp))
    lines += ["]", "", "/-- The value of a parameter as a float (AP_Param's get()). -/",
              "def get (a : All) (name : String) : Option Binary32 :="]
    first = True
    for n, f, path, e, ns in allp:
        lines.append("  %sif name == \"%s\" then some (%s)" % ("" if first else "else ", n, getter(e, "a.%s.%s" % (f, path))))
        first = False
    lines.append("  else none")
    lines += ["", "/-- Set every parameter of this name (AP_Param::set_value); none if there is none. -/",
              "def set (a : All) (name : String) (v : Binary32) : Option All := Id.run do",
              "  let mut a := a", "  let mut found := false"]
    for n, f, path, e, ns in allp:
        lines.append("  if name == \"%s\" then" % n)
        lines.append("    a := { a with %s.%s := %s }" % (f, path, setter(e, "v")))
        lines.append("    found := true")
    lines += ["  return if found then some a else none", "", "end VehicleParams", ""]
    sys.stdout.write("\n".join(lines))


if __name__ == "__main__":
    main()
